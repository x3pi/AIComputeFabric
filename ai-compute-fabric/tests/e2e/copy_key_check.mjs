// Clicks "Sao chép khóa" in real Chrome against a running gateway: legacy tenant -> rotate prompt -> key shown + copied;
// then a second click returns the same key. Usage: node copy_key_check.mjs BASE ADMIN_TOKEN
import { chromium } from "playwright-core";
import { existsSync } from "node:fs";
const [BASE, TOK] = process.argv.slice(2);
const CHROME = ["/usr/bin/google-chrome", "/usr/bin/google-chrome-stable"].find(existsSync);
const b = await chromium.launch({ executablePath: CHROME, headless: true });
const ctx = await b.newContext({ permissions: ["clipboard-read", "clipboard-write"] });
const p = await ctx.newPage();
p.on("dialog", d => (d.type() === "prompt" ? d.accept(TOK) : d.accept()));
await p.goto(BASE + "/tenants.html");
const btn = p.locator("#rows button", { hasText: "Sao chép khóa" }).first();
await btn.waitFor();
console.log("button enabled:", await btn.isEnabled());
await btn.click();
await p.waitForFunction(() => document.getElementById("keytext").textContent.startsWith("aicf_"));
const k1 = await p.textContent("#keytext");
const clip = await p.evaluate(() => navigator.clipboard.readText());
console.log("key shown:", k1.slice(0, 10) + "…", "copied to clipboard:", clip === k1, "| button:", await p.textContent("#copy"));
await p.click("#dismiss");
await p.locator("#rows button", { hasText: "Sao chép khóa" }).first().click();
await p.waitForFunction(() => document.getElementById("keytext").textContent.startsWith("aicf_"));
console.log("second click returns same key:", (await p.textContent("#keytext")) === k1);
await b.close();
